const SEVERITY_STYLE: Record<Severity, { cls: string; label: string }> = {
  CRITICAL: { cls: "bg-sev-critical-bg text-sev-critical-fg ring-sev-critical-fg/30", label: "Critical" },
  HIGH: { cls: "bg-sev-high-bg text-sev-high-fg ring-sev-high-fg/30", label: "High" },
  MEDIUM: { cls: "bg-sev-medium-bg text-sev-medium-fg ring-sev-medium-fg/30", label: "Medium" },
  LOW: { cls: "bg-sev-low-bg text-sev-low-fg ring-sev-low-fg/30", label: "Low" },
};

const SEVERITY_SHAPE: Record<Severity, string> = {
  CRITICAL: "M6 1 11 11H1z",
  HIGH: "M6 1 11 6 6 11 1 6z",
  MEDIUM: "M2 2h8v8H2z",
  LOW: "M6 2a4 4 0 1 1 0 8 4 4 0 0 1 0-8z",
};

/** Colour plus a distinct shape, so severity never depends on colour alone. */
export function SeverityBadge({ severity, className }: { severity: Severity | undefined; className?: string }) {
  if (!severity) return null;
  const s = SEVERITY_STYLE[severity];
  return (
    <span className={cn("inline-flex items-center gap-1.5 rounded-pill px-2 py-0.5 text-2xs font-bold ring-1 ring-inset", s.cls, className)}>
      <svg viewBox="0 0 12 12" className="size-2.5 fill-current" aria-hidden>
        <path d={SEVERITY_SHAPE[severity]} />
      </svg>
      {s.label}
      <span className="sr-only"> severity</span>
    </span>
  );
}

// ---------------------------------------------------------------------------

export function CitationLink({
  citation,
  slot = "primary",
  verified,
  compact = false,
}: {
  citation: Partial<Citation> | undefined;
  slot?: DocSlot;
  verified?: boolean;
  compact?: boolean;
}) {
  const { focusCitation } = useWorkspace();
  if (!citation?.page || !citation.excerpt) return null;
  const { page, excerpt, clause } = citation;
  return (
    <button
      type="button"
      onClick={() => focusCitation({ page, excerpt }, slot)}
      className={cn(
        "group block w-full rounded-control border-l-2 border-highlight bg-highlight/10 text-left transition-colors hover:bg-highlight/25",
        compact ? "px-2.5 py-1.5" : "px-3 py-2",
      )}
      aria-label={`Show page ${page}${clause ? `, ${clause}` : ""} in the document`}
    >
      <span className="flex items-center gap-2 text-2xs font-semibold text-ink-soft">
        <Quote className="size-3" aria-hidden />
        <span>
          Page {page}
          {clause ? `, ${clause}` : ""}
        </span>
        {verified === true && (
          <span className="ml-auto inline-flex items-center gap-1 text-seal" title="Quote found in your document">
            <BookOpenCheck className="size-3" aria-hidden /> Verified quote
          </span>
        )}
        {verified === false && (
          <span className="ml-auto inline-flex items-center gap-1 text-amber" title="Could not match this quote exactly">
            <AlertTriangle className="size-3" aria-hidden /> Unverified
          </span>
        )}
      </span>
      {!compact && <span className="mt-1 block font-serif text-sm italic leading-snug text-ink/85 line-clamp-3">&ldquo;{excerpt}&rdquo;</span>}
    </button>
  );
}

