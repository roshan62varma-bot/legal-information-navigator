/** Marks exactly where Gemini is working, and which model answered. */
export function GenAiStatus({
  state,
  model,
  label,
  onStop,
}: {
  state: "idle" | "streaming" | "done" | "error";
  model?: string | null;
  label: string;
  onStop?: () => void;
}) {
  return (
    <div className="flex flex-wrap items-center gap-2 text-xs" aria-live="polite">
      <span
        className={cn(
          "inline-flex items-center gap-1.5 rounded-pill px-2.5 py-1 font-semibold",
          state === "streaming" ? "bg-highlight text-highlight-ink" : "bg-ink/5 text-ink-soft",
        )}
      >
        <Sparkles className={cn("size-3.5", state === "streaming" && "animate-pulse-soft")} aria-hidden />
        {state === "streaming" ? `Gemini is ${label}` : state === "done" ? "Generated by Gemini" : "Gemini"}
      </span>
      {model && <span className="text-ink-soft">{model}</span>}
      {state === "streaming" && onStop && (
        <Button variant="ghost" size="sm" onClick={onStop} className="ml-auto">
          <CircleStop aria-hidden /> Stop
        </Button>
      )}
    </div>
  );
}

export function StreamingCaret({ show }: { show: boolean }) {
  if (!show) return null;
  return <span className="ml-0.5 inline-block h-[1.05em] w-[2px] translate-y-[2px] animate-caret-blink bg-ink align-baseline" aria-hidden />;
}

export function ErrorNotice({ message, onRetry }: { message: string; onRetry?: () => void }) {
  return (
    <div role="alert" className="flex items-start gap-3 rounded-control border border-redline/30 bg-redline/5 p-3 text-sm">
      <CircleSlash className="mt-0.5 size-4 shrink-0 text-redline" aria-hidden />
      <p className="flex-1 text-ink">{message}</p>
      {onRetry && (
        <Button variant="secondary" size="sm" onClick={onRetry}>
          Try again
        </Button>
      )}
    </div>
  );
}

export function SectionHeading({ children, count }: { children: React.ReactNode; count?: number }) {
  return (
    <h3 className="mb-2 flex items-baseline gap-2 font-sans text-sm font-bold text-ink">
      {children}
      {count !== undefined && <span className="font-normal text-ink-soft">{count}</span>}
    </h3>
  );
}

export function SkeletonLines({ lines = 3 }: { lines?: number }) {
  return (
    <div className="space-y-2" aria-hidden>
      {Array.from({ length: lines }, (_, i) => (
        <div key={i} className="h-3 animate-pulse-soft rounded-sheet bg-ink/10" style={{ width: `${92 - i * 14}%` }} />
      ))}
    </div>
  );
}

/** Renders scrubbed text with PII placeholders styled as tokens. */
export function WithPiiTokens({ text }: { text: string }) {
  const parts = text.split(/(\[(?:NAME|EMAIL|PHONE|ADDRESS|ID|BANK|CARD)_\d+\])/g);
  return (
    <>
      {parts.map((p, i) =>
        /^\[(?:NAME|EMAIL|PHONE|ADDRESS|ID|BANK|CARD)_\d+\]$/.test(p) ? (
          <span key={i} className="pii-token" title="Personal detail removed before analysis">
            {p.slice(1, -1).replace("_", " ").toLowerCase()}
          </span>
        ) : (
          <React.Fragment key={i}>{p}</React.Fragment>
        ),
      )}
    </>
  );
}
